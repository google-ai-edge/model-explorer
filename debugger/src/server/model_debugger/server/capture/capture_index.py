def anchor_key(layer: int, anchor: str) -> str:
  """The key of a PyTorch runner's tensor of an anchor of a layer."""
  return f'post_anchor_{layer}_{anchor}'


def module_key(module: str, edge: str) -> str:
  """The key of a PyTorch runner's tensor of a module asked for."""
  return f'{MODULE_PREFIX}{module}_{edge}'


class RejectedError(Exception):
  """The index rejected the contents of a turn.

  Attributes:
      n: The turn.
      side: The side whose files or completion it rejected.
      reason: Why, as the check that failed says it.
  """

  def __init__(self, n: int, side: str, reason: str) -> None:
    """Initializes the rejection of turn `n` of `side`, for `reason`."""
    super().__init__(f'The capture index rejected turn {n}: {reason}')
    self.n = n
    self.side = side
    self.reason = reason


# The old name, still used by service/ and session/ tests.
Rejected = RejectedError


def rejection(turn: dict[str, Any]) -> str:
  """Returns what the user is told of a rejected turn.

  Args:
      turn: An entry of `CaptureIndex.rejected`.
  """
  rejected = turn['rejected']
  if rejected['on_read']:
    text = f'Turn {turn["n"]} could not be read: {rejected["reason"]}'
  else:
    text = f'The capture index rejected turn {turn["n"]}: {rejected["reason"]}'
  if rejected['side'] is not None:
    text = f'{SIDE_NAMES[rejected["side"]]}: {text}'
  return text


def ending(fixed: dict[str, Any], entry: dict[str, Any]) -> str:
  """Returns what the user is told of why a side's reply ended.

  Args:
      fixed: The side's fixed info, as `CaptureIndex.sides` holds it.
      entry: The side's entry of a derived turn.
  """
  reason = entry['stop_reason']
  if reason == 'context_full':
    tokens = fixed['load']['context_length']
    return f'Context full ({tokens} tokens)'
  if reason == 'max_output_tokens':
    tokens = fixed['chat']['options']['max_completion_tokens']
    return f'Output limit reached ({tokens} tokens)'
  return 'Stop token'


def greedy_choice(
    logits: numpy.ndarray,
) -> tuple[int | None, list[int], str | None]:
  """Returns what greedy sampling picks from one row of logits.

  The one rule of a greedy step, for the index and the analyses alike. The
  largest logit is the pick, +inf the largest of all and -inf merely a low
  one. A NaN, which compares with nothing, or a row of -inf only, leaves the
  pick to the runtime; logits tied at the top, +inf among them, leave it to
  one of the tied ids.

  Args:
      logits: One row of logits.

  Returns:
      The id of the one largest logit, or None when greedy sampling's pick
      cannot be confirmed; the ids it may have picked: that id, the ids
      tied at the top, or none at all when a NaN or a row of -inf leaves no
      id to check against; and why it cannot be confirmed, or None. The why
      follows the step's name: 'Decode step 5 ' + why (unconfirmed).
  """
  nan = int(numpy.isnan(logits).sum())
  if nan:
    return None, [], f'has {nan} of {logits.size} logits that are NaN.'
  if numpy.isneginf(logits).all():
    return None, [], f'has all {logits.size} logits at -inf.'
  top = [int(id) for id in numpy.flatnonzero(logits == logits.max())]
  if len(top) > 1:
    return (
        None,
        top,
        (
            f'has {len(top)} logits tied at the top, '
            f'{float(logits.max())!r}: {_ids(top)}.'
        ),
    )
  return top[0], top, None


@dataclasses.dataclass(frozen=True)
class Feed:
  """The forward pass that fed a position, and which of its rows did.

  Attributes:
      forward: The forward pass, as a side's turn lists it in `forwards`.
      row: Its row of the position: 0 for a decode step.
      position: The position fed.
  """

  forward: dict[str, Any]
  row: int
  position: int


def feeds(entry: dict[str, Any]) -> dict[int, Feed]:
  """Returns the forward pass that fed each position of a side's turn.

  The input's prefill chunks and the decode steps; a rewrite's chunks feed
  after the turn's reply and are not listed. The last token generated,
  which no step of its turn fed, has none.

  Args:
      entry: The side's entry of a derived turn.
  """
  rewritten = {token['forward'] for token in entry['rewrite']}
  found = {}
  for forward in entry['forwards']:
    if forward['id'] in rewritten:
      continue
    first, last = (
        forward['input_positions'][0],
        forward['input_positions'][-1],
    )
    for position in range(first, last + 1):
      found[position] = Feed(forward, position - first, position)
  return found


def unconfirmed(step: int, why: str) -> str:
  """Returns why a decode step's greedy pick cannot be confirmed.

  Args:
      step: The decode step's label.
      why: greedy_choice's reason.
  """
  return f'Decode step {step} {why}'


def completion_dict(completion: runner_pb2.Completion) -> dict[str, Any]:
  """Returns a runner's Completion as the index stores it.

  Args:
      completion: The runner's Completion of a turn.

  Raises:
      ValueError: The Completion lacks what a turn needs.
  """
  if completion.finish_reason not in _FINISH_REASONS:
    raise ValueError('The runner reported no finish reason.')
  if not completion.HasField('model_debugger'):
    raise ValueError("The runner's completion has no model_debugger part.")
  debugger = completion.model_debugger
  return {
      'content': completion.content,
      'reasoning_content': completion.reasoning_content,
      'finish_reason': _FINISH_REASONS[completion.finish_reason],
      'usage': {
          'prompt_tokens': completion.usage.prompt_tokens,
          'completion_tokens': completion.usage.completion_tokens,
          'total_tokens': completion.usage.total_tokens,
      },
      'turn': debugger.turn,
      'context_token_count': debugger.context_token_count,
      'fed_tokens': [_fed_token(token) for token in debugger.fed_tokens],
  }


def turn_message(turn: dict[str, Any], side: str) -> dict[str, Any]:
  """Returns what a side of a turn was sent, as the index keeps it.

  `{role, content}`: the user's `prompt`, unless an older server kept the
  side's own message.

  Args:
      turn: An entry of `CaptureIndex.turns` or `CaptureIndex.rejected`.
      side: The side.
  """
  message = turn['sides'][side].get('message')
  if message is None:
    return {'role': 'user', 'content': turn['prompt']}
  return dict(message)


def _fed_token(token: runner_pb2.FedToken) -> dict[str, Any]:
  """Returns one token the runner says it fed, as the index stores it.

  A token of no phase is stored as the runner reported it, its phase None:
  adding the turn rejects it, and keeps its files as the evidence.

  Args:
      token: One of the runner's `fed_tokens`.
  """
  known = token.HasField('id')
  return {
      'position': token.position,
      'phase': _PHASES.get(token.phase),
      'id': token.id if known else None,
      'text': token.text if known else None,
  }


def side_entry(
    *,
    model_sha256: str,
    model_name: str,
    model_size: int,
    device_id: str,
    device_name: str,
    info: runner_pb2.RunnerInfo,
    load: runner_pb2.LoadRequest,
    chat: runner_pb2.CreateChatRequest,
    loaded: runner_pb2.LoadResponse,
) -> dict[str, Any]:
  """Returns the fixed facts of one side of a chat, as index.json keeps them.

  Args:
      model_sha256: The model file's SHA-256.
      model_name: What the user knows the model by.
      model_size: The model file's size in bytes.
      device_id: The device the side ran on.
      device_name: What the user knows the device by.
      info: What the side's runner answered GetInfo with.
      load: The side's Load request.
      chat: The side's CreateChat request.
      loaded: What the side's runner answered Load with.
  """
  stop_tokens = []
  for token in loaded.stop_tokens:
    if token.WhichOneof('token') == 'ids':
      stop_tokens.append(list(token.ids.ids))
    else:
      stop_tokens.append({'text': token.text})
  return {
      'model': {
          'sha256': model_sha256,
          'name': model_name,
          'size': model_size,
      },
      'runtime': {
          'name': _RUNTIME_NAMES.get(info.runtime.name, 'LiteRT-LM'),
          'version': info.runtime.version,
      },
      'host': json_format.MessageToDict(
          info.host, preserving_proto_field_name=True
      ),
      'device_id': device_id,
      'device_name': device_name,
      'load': {
          'device': runner_pb2.Device.Name(load.device),
          'context_length': load.context_length,
          'runtime_options': json_format.MessageToDict(load.runtime_options),
      },
      'chat': {
          'messages': [
              {
                  'role': (
                      runner_pb2.ChatMessage.Role.Name(message.role).lower()
                  ),
                  'content': message.content,
              }
              for message in chat.messages
          ],
          'options': json_format.MessageToDict(
              chat.options, preserving_proto_field_name=True
          ),
      },
      'start_token': (
          loaded.start_token if loaded.HasField('start_token') else None
      ),
      'stop_tokens': stop_tokens,
      'sampler_defaults': json_format.MessageToDict(
          loaded.sampler_defaults, preserving_proto_field_name=True
      ),
  }


class CaptureIndex:
  """A chat's capture directory and its index.

  Attributes:
      root: The capture directory.
      sides: Per side, what is fixed for the chat's life.
      turns: One entry per captured turn derived, in order: `n`, `prompt` and
        per side the recorded `completion`, `files` and `message` (what the side
        was sent, where an older server kept it; turn_message), and what is
        derived from them: `dir`, `stop_reason`, `input`, `output`, `rewrite`
        (what the turn fed after its decode steps, rewriting the context from
        the first one's position; empty for most turns), `forwards` (each with
        the files it holds by key, `tensors`, and how many rows it feeds,
        padding included, `rows`) and `kv`.
      rejected: The turns after those, in order, none derived: `n`, `prompt`,
        `rejected` (`side`, the side rejected, or None; `reason`; `on_read`,
        whether it was rejected as the index was read rather than as the turn
        was added) and per side the recorded `completion` and `files`, and
        `dir`. A turn rejected as it was added ended its
        chat: no turn follows it.
  """

  def __init__(
      self,
      root: pathlib.Path,
      sides: dict[str, Any],
      turns: list[dict[str, Any]],
  ) -> None:
    """Wraps a capture whose turns are derived; use `create` or `load`."""
    self.root = root
    self.sides = sides
    self.turns = turns
    self.rejected: list[dict[str, Any]] = []

  @classmethod
  def create(cls, root: pathlib.Path, sides: dict[str, Any]) -> 'CaptureIndex':
    """Starts the capture of a chat that has no turn yet.

    Args:
        root: The chat's capture directory; created.
        sides: Per side (`ref`, `target`), what is fixed for the chat's
          life: `model`, `runtime`, `host`, `device_id`, `device_name`, `load`
            (with `context_length`), `chat`, `start_token` (or None),
            `stop_tokens` (each a list of ids, or `{"text": ...}`) and
            `sampler_defaults` (the model's own sampling the runner reported, by
            LoadResponse's field names; absent from an index.json written before
            it was kept).
    """
    root.mkdir(parents=True, exist_ok=True)
    capture = cls(root, sides, [])
    capture._write()
    return capture

  @classmethod
  def load(cls, root: pathlib.Path) -> 'CaptureIndex':
    """Reads a chat's capture and derives its turns from their facts.

    A turn recorded as rejected stays so; a turn that cannot be derived
    is rejected on read, and so is every turn after it.

    Raises:
        NotFound: The chat has no capture.
        ValueError: The index is of another format version, or its turns
          are out of order.
    """
    path = root / _INDEX
    if not path.is_file():
      raise errors.NotFoundError('This chat has no capture.')
    index = json_file.read_json(path)
    if index.get('format_version') != FORMAT_VERSION:
      raise ValueError(
          f'The capture in {root} has format version '
          f'{index.get("format_version")}; this server reads '
          f'{FORMAT_VERSION}.'
      )
    capture = cls(root, index['sides'], [])
    for stored in index['turns']:
      n = capture.next_turn()
      if stored['n'] != n:
        raise ValueError(
            f'The capture in {root} has turn {stored["n"]} after turn {n - 1}.'
        )
      prompt = stored['prompt']
      completions = {
          side: stored['sides'][side]['completion'] for side in capture.sides
      }
      files = {side: stored['sides'][side]['files'] for side in capture.sides}
      messages = {
          side: stored['sides'][side]['message']
          for side in capture.sides
          if 'message' in stored['sides'][side]
      }
      recorded = stored.get('rejected')
      if recorded is not None:
        why = (recorded['side'], recorded['reason'], False)
      elif capture.rejected:
        reason = f'It follows turn {n - 1}, which was rejected.'
        why = (None, reason, True)
      else:
        try:
          turn = capture._derive_turn(n, prompt, completions, files, messages)
        except RejectedError as error:
          why = (error.side, error.reason, True)
        else:
          capture.turns.append(turn)
          continue
      capture.rejected.append(
          _rejected_turn(n, prompt, completions, files, messages, *why)
      )
    return capture

  def turn_directory(self, side: str, n: int) -> pathlib.Path:
    """Returns where the files of turn `n` of `side` go; made if missing."""
    directory = self.root / side / f'turn-{n}'
    directory.mkdir(parents=True, exist_ok=True)
    return directory

  def add_turn(
      self,
      n: int,
      prompt: str,
      completions: dict[str, dict[str, Any]],
  ) -> None:
    """Indexes the files of turn `n`, already in its turn directories.

    Args:
        n: The turn; must follow the last captured one.
        prompt: The user message of the turn.
        completions: Per side, `completion_dict` of the runner's Completion.

    Raises:
        ValueError: The turn is out of order, or follows a rejected one.
        RejectedError: The files contradict the completion, or cannot be read;
          the turn is recorded as rejected, its files kept.
    """
    if self.rejected:
      raise ValueError(
          f'Turn {n} cannot follow turn {self.rejected[-1]["n"]}, which '
          'was rejected.'
      )
    if n != len(self.turns) + 1:
      raise ValueError(f'Turn {n} cannot follow turn {len(self.turns)}.')
    if set(completions) != set(self.sides):
      raise ValueError(
          f'Turn {n} has completions for {sorted(completions)}, '
          f'not for {sorted(self.sides)}.'
      )
    files = {
        side: _list_files(self.turn_directory(side, n)) for side in self.sides
    }
    messages = {}  # turn_message() reads `prompt`.
    try:
      entry = self._derive_turn(n, prompt, completions, files, messages)
    except RejectedError as rejected:
      self.rejected.append(
          _rejected_turn(
              n,
              prompt,
              completions,
              files,
              messages,
              rejected.side,
              rejected.reason,
              False,
          )
      )
      try:
        self._write()
      except BaseException:
        self.rejected.pop()
        raise
      raise
    self.turns.append(entry)
    try:
      self._write()
    except BaseException:
      self.turns.pop()
      raise

  def snapshot(self) -> 'CaptureIndex':
    """Returns the capture as it is now, to read while turns are added.

    Its `turns` and `rejected` are copies, which add_turn does not
    change; the entries are shared. Only read it: it names the same
    directory.
    """
    copy = CaptureIndex(self.root, self.sides, list(self.turns))
    copy.rejected = list(self.rejected)
    return copy

  def next_turn(self) -> int:
    """Returns the number of the turn after the last one recorded."""
    return len(self.turns) + len(self.rejected) + 1

  def turn(self, n: int) -> dict[str, Any]:
    """Returns the entry of turn `n`.

    Args:
        n: The turn.

    Raises:
        NotFound: Turn `n` has no capture.
        Conflict: Turn `n` was rejected; the message says why.
    """
    if 1 <= n <= len(self.turns):
      return self.turns[n - 1]
    for rejected in self.rejected:
      if rejected['n'] == n:
        raise errors.ConflictError(rejection(rejected))
    raise errors.NotFoundError(f'Turn {n} has no capture.')

  def path(self, side: str, n: int, file: str) -> pathlib.Path:
    """Returns the path of a file the index names for turn `n` of `side`."""
    return self.root / self.turn(n)['sides'][side]['dir'] / file

  def _derive_turn(
      self,
      n: int,
      prompt: str,
      completions: dict[str, dict[str, Any]],
      files: dict[str, list[dict[str, Any]]],
      messages: dict[str, dict[str, Any]],
  ) -> dict[str, Any]:
    """Returns the entry of turn `n`, derived from its facts and files.

    Args:
        n: The turn; follows the last one in `turns`.
        prompt: What the turn says, the Reference's message's content.
        completions: Per side, `completion_dict` of the runner's Completion.
        files: Per side, the turn's files as `{path, size}`.
        messages: Per side, what it was sent, where an older server kept it.

    Raises:
        RejectedError: The files are not as recorded, or contradict each other
          or the completion.
    """
    previous = self.turns[-1]['sides'] if self.turns else {}
    sides = {}
    # Ref first, in whatever order the sides started: a rejection names
    # the first side rejected.
    for side in sorted(self.sides, key=SIDES.index):
      fixed = self.sides[side]
      directory = self.root / side / f'turn-{n}'
      try:
        _check_files(directory, files[side])
        entry = _read_side_turn(
            directory,
            fixed,
            completions[side],
            files[side],
            previous.get(side),
            n,
        )
      except _UNREADABLE as error:
        raise RejectedError(n, side, str(error)) from error
      entry['dir'] = f'{side}/turn-{n}'
      if side in messages:
        entry['message'] = messages[side]
      sides[side] = entry
    return {'n': n, 'prompt': prompt, 'sides': sides}

  def _write(self) -> None:
    """Writes index.json: the fixed facts and each turn's facts only."""
    json_file.write_json(
        self.root / _INDEX,
        {
            'format_version': FORMAT_VERSION,
            'sides': self.sides,
            'turns': [
                _stored_turn(turn) for turn in self.turns + self.rejected
            ],
        },
    )


def _stored_turn(turn: dict[str, Any]) -> dict[str, Any]:
  """Returns what index.json keeps of a turn: its facts only.

  A rejection on read is not one: it is derived whenever the index is read.

  Args:
      turn: An entry of `CaptureIndex.turns` or `CaptureIndex.rejected`.
  """
  stored = {'n': turn['n'], 'prompt': turn['prompt']}
  rejected = turn.get('rejected')
  if rejected is not None and not rejected['on_read']:
    stored['rejected'] = {
        'side': rejected['side'],
        'reason': rejected['reason'],
    }
  stored['sides'] = {
      side: {key: entry[key] for key in _SIDE_TURN_FACTS if key in entry}
      for side, entry in turn['sides'].items()
  }
  return stored


def _rejected_turn(
    n: int,
    prompt: str,
    completions: dict[str, dict[str, Any]],
    files: dict[str, list[dict[str, Any]]],
    messages: dict[str, dict[str, Any]],
    side: str | None,
    reason: str,
    on_read: bool,
) -> dict[str, Any]:
  """Returns the entry of a rejected turn: its facts and why, not derived.

  Args:
      n: The turn.
      prompt: What the turn says, the Reference's message's content.
      completions: Per side, `completion_dict` of the runner's Completion.
      files: Per side, the turn's files as `{path, size}`.
      messages: Per side, what it was sent, where kept.
      side: The side rejected, or None for a turn rejected because the one
        before it was.
      reason: Why.
      on_read: Whether it is rejected as the index is read, rather than as the
        turn was added.
  """
  return {
      'n': n,
      'prompt': prompt,
      'rejected': {'side': side, 'reason': reason, 'on_read': on_read},
      'sides': {
          name: {
              'completion': completions[name],
              'files': files[name],
              'dir': f'{name}/turn-{n}',
              **({'message': messages[name]} if name in messages else {}),
          }
          for name in completions
      },
  }


def _check_files(directory: pathlib.Path, files: list[dict[str, Any]]) -> None:
  """Checks that a turn's files are there, of the sizes recorded.

  Args:
      directory: The turn's directory.
      files: The turn's files as `{path, size}`.

  Raises:
      ValueError: A file is missing, or of another size.
  """
  for file in files:
    try:
      size = (directory / file['path']).stat().st_size
    except FileNotFoundError:
      raise ValueError(f'{file["path"]} is missing.') from None
    if size != file['size']:
      raise ValueError(
          f'{file["path"]} holds {size} bytes; the capture recorded '
          f'{file["size"]}.'
      )


def _read_side_turn(
    directory: pathlib.Path,
    fixed: dict[str, Any],
    completion: dict[str, Any],
    files: list[dict[str, Any]],
    previous: dict[str, Any] | None,
    n: int,
) -> dict[str, Any]:
  """Derives one side's entry of turn `n` from its files and its completion.

  Args:
      directory: The turn's directory.
      fixed: The side's fixed info (`start_token`, `stop_tokens`, `load`).
      completion: The side's `completion_dict`.
      files: The turn's files as `{path, size}`.
      previous: The side's entry of turn `n - 1`, or None for turn 1.
      n: The turn.

  Returns:
      The side's derived entry of the turn.

  Raises:
      ValueError: The files contradict each other or the completion.
  """
  if completion['turn'] != n:
    raise ValueError(f'The runner calls turn {n} turn {completion["turn"]}.')
  calls = _calls(directory, files)
  _check_observed(calls)
  observation = _observation(directory, files, calls)
  released = _released(directory / _TOKENS)
  context_length = fixed['load']['context_length']
  stop_ids = {
      token[0]
      for token in fixed['stop_tokens']
      if isinstance(token, list) and len(token) == 1
  }
  # The tokens the runner says the turn fed.
  fed = completion.get('fed_tokens')
  if fed is None:
    raise ValueError(
        f'Turn {n} was captured by a runner from before fed_tokens; '
        'such captures are no longer read. Capture the chat again.'
    )
  if not fed:
    raise ValueError(
        f'The runner reported no fed tokens for turn {n}: it was built '
        'before it reported them; rebuild it.'
    )
  for token in fed:
    if token['phase'] is None:
      raise ValueError(
          'The runner reports a fed token at position '
          f'{token["position"]} of no phase.'
      )

  # Forward passes, checked to feed consecutive positions: the input's
  # prefill chunks, the decode steps, then the chunks of a rewrite.
  prefills, decodes = [], []
  for (signature, step), call in calls.items():
    if signature == 'decode':
      position = _decode_position(directory, signature, step, call)
      decodes.append((step, signature, call, position))
    elif signature.startswith('prefill'):
      first, last = _prefill_positions(directory, signature, step, call)
      prefills.append((first, last, signature, step, call))
    else:
      raise ValueError(f'Turn {n} has files of unknown signature {signature}.')
  if not decodes:
    raise ValueError(f'Turn {n} has no decode step.')
  prefills.sort()
  decodes.sort()
  # A chunk from the first decode step's position on comes after the
  # decode steps: that step wrote the position first.
  rewrites = [chunk for chunk in prefills if chunk[0] >= decodes[0][3]]
  prefills = [chunk for chunk in prefills if chunk[0] < decodes[0][3]]
  start = prefills[0][0] if prefills else decodes[0][3]
  expected = start
  for first, last, signature, step, _ in prefills:
    if first != expected:
      raise ValueError(
          f'{signature} step {step} feeds position {first}; '
          f'position {expected} comes next.'
      )
    expected = last + 1
  for step, signature, _, position in decodes:
    if position != expected:
      raise ValueError(
          f'{signature} step {step} feeds position {position}; '
          f'position {expected} comes next.'
      )
    expected += 1
  if rewrites and rewrites[0][0] > expected:
    _, _, signature, step, _ = rewrites[0]
    raise ValueError(
        f'{signature} step {step} feeds position {rewrites[0][0]}; the '
        f'decode steps end at position {expected - 1}.'
    )
  expected = rewrites[0][0] if rewrites else None
  for first, last, signature, step, _ in rewrites:
    if first != expected:
      raise ValueError(
          f'{signature} step {step} feeds position {first}; '
          f'position {expected} comes next.'
      )
    expected = last + 1
  # The first decode step feeds the last input token.
  last_input = decodes[0][3]

  _check_fed(fed, prefills, decodes, rewrites)
  inputs = _fed_input(fed[: last_input - start + 1], fixed, previous, start, n)

  forwards = []
  for first, last, signature, step, call in prefills:
    forwards.append(
        _prefill_forward(len(forwards), first, last, signature, step, call)
    )
  vocabulary = None
  # Per decode forward, the ids greedy sampling may have picked, and why
  # its pick cannot be confirmed, if it cannot.
  choices = {}
  for step, signature, call, position in decodes:
    logits = tensor_file.read_tensor(directory / _need(call, 'post_logits')[0])
    rows = logits.reshape(-1, logits.shape[-1])
    if rows.shape[0] != 1:
      raise ValueError(
          f'{signature} step {step} has {rows.shape[0]} rows of logits.'
      )
    if vocabulary not in (None, rows.shape[1]):
      raise ValueError(f'{signature} step {step} changes the vocabulary size.')
    vocabulary = rows.shape[1]
    argmax, top, reason = greedy_choice(rows[0])
    choices[len(forwards)] = (top, reason)
    forwards.append({
        'id': len(forwards),
        'signature': signature,
        'phase': 'decode',
        'step': step,
        'input_position': position,
        'input_positions': [position],
        'tensors': {key: name for key, (name, _) in sorted(call.items())},
        'rows': 1,
        'argmax': argmax,
    })
  # The rewrite's rows are the last the runner lists, in position order.
  rewrite = []
  said = fed[len(fed) - (expected - rewrites[0][0]) :] if rewrites else []
  for first, last, signature, step, call in rewrites:
    forward = _prefill_forward(
        len(forwards), first, last, signature, step, call
    )
    forwards.append(forward)
    for position in range(first, last + 1):
      token = said[position - rewrites[0][0]]
      rewrite.append({
          'id': token['id'],
          'text': token['text'],
          'position': position,
          'forward': forward['id'],
      })

  # What the decode steps generated: the released tokens, as the jsonl
  # names them, then perhaps a stop token, which the runtime does not
  # release. Of a greedy chat (top_k 1) that stop token is the step's
  # argmax, when that is one stop token; of another sampler, or when it is
  # not, its id is unknown. A greedy step whose logits name no one argmax
  # (greedy_choice) cannot be confirmed, and its token says so.
  greedy = fixed['chat']['options'].get('top_k') == 1
  generated = [forward for forward in forwards if forward['phase'] == 'decode']
  if not len(released) <= len(generated) <= len(released) + 1:
    raise ValueError(
        f'Turn {n} has {len(generated)} decode steps for '
        f'{len(released)} released tokens.'
    )
  output = []
  for index, forward in enumerate(generated):
    token = {
        'id': None,
        'text': None,
        'position': forward['input_position'] + 1,
        'forward': forward['id'],
        'released': index < len(released),
    }
    top, reason = choices[forward['id']]
    if greedy and reason is not None:
      token['cannot_confirm'] = unconfirmed(forward['step'], reason)
    if index < len(released):
      token['id'], token['text'] = released[index]
    else:
      token['stop'] = True
      if greedy and len(stop_ids & set(top)) == 1:
        (token['id'],) = stop_ids & set(top)
    output.append(token)

  usage = completion['usage']
  if usage['completion_tokens'] != len(output):
    raise ValueError(
        f'The runner counts {usage["completion_tokens"]} completion '
        f'tokens; turn {n} has {len(output)} decode steps.'
    )
  _check_fed_decodes(fed[last_input - start :], output, generated)
  _check_counts(completion, last_input, fed[-1]['position'], n)
  stop_reason = _stop_reason(
      completion, fixed, output[-1].get('stop', False), n
  )

  # The KV cache before and after the input's prefill, and after the last
  # decode step, which is before any rewrite.
  kv = []
  if prefills:
    first, _, _, step, call = prefills[0]
    layers = _kv_layers(call, 'pre', context_length)
    if layers:
      kv.append({
          'moment': 'prefill_pre',
          'step': step,
          'processed': first,
          'layers': layers,
      })
    _, last, _, step, call = prefills[-1]
    layers = _kv_layers(call, 'post', context_length)
    if layers:
      kv.append({
          'moment': 'prefill_post',
          'step': step,
          'processed': last + 1,
          'layers': layers,
      })
  for index, (step, signature, call, position) in enumerate(decodes):
    layers = _kv_layers(call, 'post', context_length)
    if layers and index != len(decodes) - 1:
      raise ValueError(
          f'{signature} step {step} wrote the KV cache before the last '
          'decode step.'
      )
    if layers:
      kv.append({
          'moment': 'terminal',
          'step': step,
          'processed': position + 1,
          'layers': layers,
      })

  return {
      'completion': completion,
      'stop_reason': stop_reason,
      'input': inputs,
      'output': output,
      'rewrite': rewrite,
      'forwards': forwards,
      'kv': kv,
      'observation': observation,
      'files': files,
  }


def _observation(
    directory: pathlib.Path,
    files: list[dict[str, Any]],
    calls: dict[
        tuple[str, int], dict[str, tuple[str, tensor_file.TensorHeader]]
    ],
) -> dict[str, Any] | None:
  """What a turn says it observed (OBSERVATION), checked against its files.

  Args:
      directory: The turn's directory.
      files: The turn's files as `{path, size}`.
      calls: The turn's tensors, as `_calls` groups them.

  Returns:
      The contents of OBSERVATION, or None when the turn has no such file.

  Raises:
      ValueError: The file is not what a runner writes, an anchor's file
        names another layer or anchor than its key, or a turn that says
        it captured no anchors holds some.
  """
  anchors = 0
  for call in calls.values():
    for key, (name, header) in call.items():
      module = _MODULE_KEY.fullmatch(key)
      if module is not None:
        anchors += 1
        said = (
            header.metadata.get('module'),
            header.metadata.get('edge'),
        )
        if said != module.groups():
          raise ValueError(
              f'{name} holds {key}, but says it is module '
              f'{said[0]}, edge {said[1]}.'
          )
        continue
      match = _ANCHOR_KEY.fullmatch(key)
      if match is None:
        continue
      anchors += 1
      said = (header.metadata.get('layer'), header.metadata.get('anchor'))
      if said != match.groups():
        raise ValueError(
            f'{name} holds {key}, but says it is layer {said[0]}, '
            f'anchor {said[1]}.'
        )
  if not any(file['path'] == OBSERVATION for file in files):
    return None
  facts = json.loads((directory / OBSERVATION).read_text('utf-8'))
  if not (
      isinstance(facts, dict)
      and isinstance(facts.get('captured'), bool)
      and isinstance(facts.get('reason'), str)
  ):
    raise ValueError(f'{OBSERVATION} says no `captured` and `reason`.')
  if anchors and not facts['captured']:
    raise ValueError(
        f'{OBSERVATION} says the turn captured no anchors; it holds {anchors}.'
    )
  return facts


def _prefill_forward(
    forward_id: int,
    first: int,
    last: int,
    signature: str,
    step: int,
    call: dict[str, tuple[str, tensor_file.TensorHeader]],
) -> dict[str, Any]:
  """Returns the entry of a prefill chunk's forward pass."""
  return {
      'id': forward_id,
      'signature': signature,
      'phase': 'prefill',
      'step': step,
      'input_positions': [first, last],
      'tensors': {key: name for key, (name, _) in sorted(call.items())},
      'rows': math.prod(_need(call, 'pre_input_pos')[1].shape),
  }


def _check_observed(
    calls: dict[
        tuple[str, int], dict[str, tuple[str, tensor_file.TensorHeader]]
    ],
) -> None:
  """Checks that each signature's observed tensors name one subgraph.

  Args:
      calls: The turn's tensors, as `_calls` groups them.

  Raises:
      ValueError: Two files of a signature name two subgraphs.
  """
  subgraphs = {}
  for (signature, _), call in sorted(calls.items()):
    for key, (name, _) in sorted(call.items()):
      added = tap_model.added_point(key)
      if added is None:
        continue
      first = subgraphs.setdefault(signature, (added[0], name))
      if first[0] != added[0]:
        raise ValueError(
            f'{name} observes subgraph {added[0]} of {signature}, '
            f'and {first[1]} subgraph {first[0]}.'
        )


def _check_fed(
    fed: list[dict[str, Any]],
    prefills: list[
        tuple[
            int, int, str, int, dict[str, tuple[str, tensor_file.TensorHeader]]
        ]
    ],
    decodes: list[
        tuple[int, str, dict[str, tuple[str, tensor_file.TensorHeader]], int]
    ],
    rewrites: list[
        tuple[
            int, int, str, int, dict[str, tuple[str, tensor_file.TensorHeader]]
        ]
    ],
) -> None:
  """Checks that the runner's fed tokens are the rows the files feed.

  Args:
      fed: The completion's `fed_tokens`.
      prefills: The input's prefill chunks, as `_read_side_turn` holds them.
      decodes: The decode steps, likewise.
      rewrites: The prefill chunks after the decode steps, likewise.

  Raises:
      ValueError: The runner's tokens are not, in order, the rows each
        forward pass fed, by phase and position.
  """
  rows = []
  for first, last, *_ in prefills:
    rows += [('prefill', position) for position in range(first, last + 1)]
  rows += [('decode', position) for *_, position in decodes]
  for first, last, *_ in rewrites:
    rows += [('prefill', position) for position in range(first, last + 1)]
  said = [(token['phase'], token['position']) for token in fed]
  for index, (row, token) in enumerate(zip(rows, said)):
    if row != token:
      raise ValueError(
          f'The runner says fed token {index} is a {token[0]} at '
          f'position {token[1]}; the files feed a {row[0]} at position '
          f'{row[1]} there.'
      )
  if len(said) != len(rows):
    raise ValueError(
        f'The runner says the turn fed {len(said)} tokens; the files feed '
        f'{len(rows)}.'
    )


def _fed_input(
    fed: list[dict[str, Any]],
    fixed: dict[str, Any],
    previous: dict[str, Any] | None,
    start: int,
    n: int,
) -> list[dict[str, Any]]:
  """Returns a turn's input from the tokens the runner says it fed.

  Args:
      fed: The fed tokens up to the first decode step's, which feeds the last
        input token.
      fixed: The side's fixed info.
      previous: The side's entry of turn `n - 1`, or None for turn 1.
      start: The first position the turn fed.
      n: The turn.

  Raises:
      ValueError: The first token is not where, or not what, the turn
        before or the model says it is.
  """
  inputs = [
      {'id': token['id'], 'text': token['text'], 'origin': 'prompt'}
      for token in fed
  ]
  lead = inputs[0]
  if previous is None:
    start_token = fixed['start_token']
    if start != 0:
      raise ValueError(f'Turn 1 first feeds position {start}, not 0.')
    if start_token is not None:
      if lead['id'] not in (None, start_token):
        raise ValueError(
            f'Turn 1 first feeds {lead["id"]}, not the start token '
            f'{start_token}.'
        )
      lead.update(id=start_token, origin='start')
  else:
    held = previous['completion']['context_token_count'] - 1
    carried = previous['output'][-1]
    if start == held:
      lead['origin'] = 'carried'
      # After a turn that ended by decoding, the token held is the
      # last it generated.
      if not previous['rewrite'] and carried['position'] == held:
        if None not in (lead['id'], carried['id']) and (
            lead['id'] != carried['id']
        ):
          raise ValueError(
              f'Turn {n} first feeds {lead["id"]}, but turn '
              f'{n - 1} generated {carried["id"]} there.'
          )
        if lead['id'] is None:
          lead.update(id=carried['id'], text=carried['text'])
    elif start < held:
      # The runtime rolled its context back to `start` and fed its own
      # rendering of the earlier turns from there before the prompt;
      # the runner does not say where one ends and the other begins.
      for token in inputs:
        token['origin'] = 'history'
    else:
      raise ValueError(
          f'Turn {n} first feeds position {start}; turn {n - 1} held '
          f'the token at position {held} back for it.'
      )
  for token, said in zip(inputs, fed):
    token['position'] = said['position']
  return inputs


def _check_fed_decodes(
    fed: list[dict[str, Any]],
    output: list[dict[str, Any]],
    generated: list[dict[str, Any]],
) -> None:
  """Checks that each decode step fed what the step before it generated.

  Only where both ids are known; the first step feeds the input's last.

  Args:
      fed: The fed tokens from the first decode step's on.
      output: The turn's generated tokens.
      generated: The decode forwards, in order.

  Raises:
      ValueError: A decode step fed another token.
  """
  for k in range(1, len(output)):
    said, made = fed[k]['id'], output[k - 1]['id']
    if None not in (said, made) and said != made:
      raise ValueError(
          f'The runner says decode step {generated[k]["step"]} fed '
          f'{said}; the step before generated {made}.'
      )


def _check_counts(
    completion: dict[str, Any], last_input: int, last_fed: int, n: int
) -> None:
  """Checks the runner's counts of a turn against the positions it fed.

  Args:
      completion: The side's `completion_dict`.
      last_input: The position the first decode step fed.
      last_fed: The position of the last token the turn fed.
      n: The turn.

  Raises:
      ValueError: A count disagrees with the positions.
  """
  usage = completion['usage']
  if usage['prompt_tokens'] != last_input + 1:
    raise ValueError(
        f'The runner counts {usage["prompt_tokens"]} prompt tokens; turn '
        f'{n} first decodes at position {last_input}.'
    )
  if usage['total_tokens'] != (
      usage['prompt_tokens'] + usage['completion_tokens']
  ):
    raise ValueError(
        f'The runner counts {usage["total_tokens"]} total tokens for '
        f'{usage["prompt_tokens"]} prompt and '
        f'{usage["completion_tokens"]} completion tokens.'
    )
  if completion['context_token_count'] != last_fed + 2:
    raise ValueError(
        f'The runner counts {completion["context_token_count"]} context '
        f'tokens; turn {n} last feeds position {last_fed}, and holds the '
        'next one.'
    )


def _stop_reason(
    completion: dict[str, Any],
    fixed: dict[str, Any],
    ended_on_stop: bool,
    n: int,
) -> str:
  """Returns why a side's reply of turn `n` ended.

  FINISH_REASON_LENGTH stands for either limit: the context's, when the
  turn's total is the Load's context_length, and the reply's own
  max_completion_tokens otherwise. A full context comes first, even after a
  stop token: no turn follows it.

  Args:
      completion: The side's `completion_dict`.
      fixed: The side's fixed info (`load`, `chat`).
      ended_on_stop: Whether the reply's last token is a stop token.
      n: The turn.

  Returns:
      'context_full', 'eos' or 'max_output_tokens'.

  Raises:
      ValueError: The runner reports LENGTH, but neither limit was reached.
  """
  usage = completion['usage']
  context_length = fixed['load']['context_length']
  length = completion['finish_reason'] == 'length'
  if length and usage['total_tokens'] >= context_length:
    return 'context_full'
  if ended_on_stop or not length:
    return 'eos'
  limit = fixed['chat']['options'].get('max_completion_tokens')
  if limit is None or usage['completion_tokens'] < limit:
    reply = (
        f'{usage["completion_tokens"]} tokens and no limit'
        if limit is None
        else f'{usage["completion_tokens"]} of {limit} tokens'
    )
    raise ValueError(
        f'The runner reports FINISH_REASON_LENGTH for turn {n}, but its '
        f'reply has {reply}, and the context {usage["total_tokens"]} of '
        f'{context_length}.'
    )
  return 'max_output_tokens'


def _ids(ids: list[int]) -> str:
  """Names a few ids, as `5`, `5 or 9`, or `5, 9, 12, ... (40 ids)`."""
  if len(ids) == 1:
    return str(ids[0])
  if len(ids) <= 3:
    return ', '.join(map(str, ids[:-1])) + f' or {ids[-1]}'
  return ', '.join(map(str, ids[:3])) + f', ... ({len(ids)} ids)'


def _list_files(directory: pathlib.Path) -> list[dict[str, Any]]:
  """Returns a turn's files as `{path, size}`, by name."""
  names = sorted(path.name for path in directory.iterdir())
  return [
      {'path': name, 'size': (directory / name).stat().st_size}
      for name in names
  ]


def _calls(
    directory: pathlib.Path, files: list[dict[str, Any]]
) -> dict[tuple[str, int], dict[str, tuple[str, tensor_file.TensorHeader]]]:
  """Groups a turn's tensors by (signature, step).

  Args:
      directory: The turn's directory.
      files: The turn's files as `{path, size}`.

  Returns:
      Per (signature, step), the tensors as `{key: (file name,
      TensorHeader)}`.
  """
  calls = {}
  names = [file['path'] for file in files]
  if _TOKENS not in names:
    raise ValueError(f'The capture in {directory} has no {_TOKENS}.')
  for name in names:
    if name in (_TOKENS, OBSERVATION, EXECUTION_GRAPH):
      continue
    if not name.endswith('.safetensors'):
      raise ValueError(f'The capture holds an unexpected file, {name}.')
    header = tensor_file.read_header(directory / name)
    signature = header.metadata.get('signature')
    step = header.metadata.get('step', '')
    if not signature or not step.isdigit():
      raise ValueError(f'{name} names no signature and step.')
    if not header.key.startswith(('pre_', 'post_')):
      raise ValueError(f'{name} holds {header.key}, not an input or output.')
    call = calls.setdefault((signature, int(step)), {})
    if header.key in call:
      raise ValueError(
          f'{name} and {call[header.key][0]} both hold {header.key} of '
          f'{signature} step {step}.'
      )
    call[header.key] = (name, header)
  return calls


def _released(path: pathlib.Path) -> list[tuple[int, str | None]]:
  """Returns the released tokens of a turn as (id, text or None)."""
  tokens = []
  for number, line in enumerate(path.read_text('utf-8').split('\n'), 1):
    if not line.strip():
      continue
    record = json.loads(line)
    ids = record.get('token_ids') if isinstance(record, dict) else None
    if not (
        isinstance(ids, list)
        and len(ids) == 1
        and isinstance(ids[0], list)
        and len(ids[0]) == 1
        and isinstance(ids[0][0], int)
        and not isinstance(ids[0][0], bool)
    ):
      raise ValueError(
          f'{_TOKENS} line {number} is not one token of one candidate.'
      )
    texts = record.get('texts')
    text = None
    if isinstance(texts, list) and len(texts) == 1:
      text = texts[0]
    tokens.append((ids[0][0], text))
  return tokens


def _need(
    call: dict[str, tuple[str, tensor_file.TensorHeader]], key: str
) -> tuple[str, tensor_file.TensorHeader]:
  """Returns the (file name, header) of `key` in a call, or raises."""
  if key not in call:
    names = ', '.join(sorted(name for name, _ in call.values()))
    raise ValueError(f'The call with files {names} has no {key}.')
  return call[key]


def _decode_position(
    directory: pathlib.Path,
    signature: str,
    step: int,
    call: dict[str, tuple[str, tensor_file.TensorHeader]],
) -> int:
  """Returns the position a decode step feeds, checked against its step."""
  positions = tensor_file.read_tensor(
      directory / _need(call, 'pre_input_pos')[0]
  )
  positions = positions.reshape(-1)
  if positions.size != 1:
    raise ValueError(
        f'{signature} step {step} feeds {positions.size} positions.'
    )
  position = int(positions[0])
  if position != step - 1:
    raise ValueError(f'{signature} step {step} feeds position {position}.')
  return position


def _prefill_positions(
    directory: pathlib.Path,
    signature: str,
    step: int,
    call: dict[str, tuple[str, tensor_file.TensorHeader]],
) -> tuple[int, int]:
  """Returns the first and last position a prefill chunk feeds.

  The valid rows are the leading run of consecutive positions; the padding
  after them has position 0. A boolean mask must attend from exactly as many
  rows.

  Args:
      directory: The turn's directory.
      signature: The chunk's signature.
      step: The chunk's step.
      call: The chunk's tensors, as `_calls` groups them.

  Returns:
      The first and the last position the chunk feeds.

  Raises:
      ValueError: The mask attends from another number of rows.
  """
  positions = tensor_file.read_tensor(
      directory / _need(call, 'pre_input_pos')[0]
  )
  positions = positions.reshape(-1)
  count = 1
  while count < positions.size and positions[count] == positions[count - 1] + 1:
    count += 1
  first = int(positions[0])
  if 'pre_mask' in call and call['pre_mask'][1].dtype == 'BOOL':
    mask = tensor_file.read_tensor(directory / call['pre_mask'][0])
    attending = int(mask.reshape(-1, mask.shape[-1]).any(axis=1).sum())
    if attending != count:
      raise ValueError(
          f'{signature} step {step} feeds {count} positions, but its '
          f'mask attends from {attending} rows.'
      )
  return first, first + count - 1


def _declared_layout(metadata: dict[str, str], kind: str) -> list[str] | None:
  """The axes a KV file's `layout` metadata names for `kind`, if any.

  The metadata is 'k:<axes>,v:<axes>', each axis a letter: b(atch),
  h (KV head), s(equence), d (head dimension), as 'k:bhsd,v:bhsd'.

  Args:
      metadata: The KV file's `__metadata__`.
      kind: 'k' or 'v'.

  Returns:
      The axis names, in order, or None when the metadata names no layout.

  Raises:
      ValueError: The metadata is there but not of that form.
  """
  text = metadata.get('layout')
  if text is None:
    return None
  parts = dict(part.split(':', 1) for part in text.split(',') if ':' in part)
  axes = parts.get(kind, '')
  if sorted(axes) != sorted(_LAYOUT_LETTERS):
    raise ValueError(f'A KV file has the layout {text!r}.')
  return [_LAYOUT_LETTERS[letter] for letter in axes]


def _kv_positions(metadata: dict[str, str]) -> list[int] | None:
  """The first and last position a KV file holds, as `kv_positions` says.

  Args:
      metadata: The KV file's `__metadata__`.

  Returns:
      `[first, last]`, or None when the metadata names no positions.

  Raises:
      ValueError: The metadata is there but not 'start-end'.
  """
  text = metadata.get('kv_positions')
  if text is None:
    return None
  match = re.fullmatch(r'(\d+)-(\d+)', text)
  if match is None or int(match.group(1)) > int(match.group(2)):
    raise ValueError(f'A KV file holds the positions {text!r}.')
  return [int(match.group(1)), int(match.group(2))]


def _kv_layers(
    call: dict[str, tuple[str, tensor_file.TensorHeader]],
    moment: str,
    context_length: int,
) -> list[dict[str, Any]]:
  """Returns the KV cache tensors of a call at `pre` or `post`, by layer."""
  layers: dict[int, dict[str, Any]] = {}
  for key, (name, header) in call.items():
    match = _KV_KEY.fullmatch(key)
    if match is None or match.group(1) != moment:
      continue
    kind = match.group(2)
    shape = list(header.shape)
    declared = _declared_layout(header.metadata, kind)
    if declared is not None:
      # A layout the file declares (the PyTorch runner's): its sequence
      # axis holds the positions processed so far, not the context.
      layout = declared if len(shape) == 4 else None
    else:
      sequence_axis = _LAYOUTS[kind].index('sequence')
      fits = len(shape) == 4 and shape[sequence_axis] == context_length
      layout = list(_LAYOUTS[kind]) if fits else None
    stored = {
        'file': name,
        'dtype': header.dtype,
        'shape': shape,
        'layout': layout,
    }
    positions = _kv_positions(header.metadata)
    if positions is not None:
      stored['positions'] = positions
    layers.setdefault(int(match.group(3)), {})[
        'key' if kind == 'k' else 'value'
    ] = stored
  for layer, parts in layers.items():
    if len(parts) != 2:
      raise ValueError(
          f'Layer {layer} has a {moment} KV cache of one kind only.'
      )
  return [{'layer': layer, **layers[layer]} for layer in sorted(layers)]
