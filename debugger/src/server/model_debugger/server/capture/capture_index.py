"""A chat's capture on disk, and the index that lines its files up.

A chat's capture lives in one directory:

  index.json
  ref/turn-<n>/<the files of turn n, named as the runner named them>
  target/turn-<n>/...

The files are LiteRT-LM's RuntimeDebugger dump: one tensor per safetensors
file, keyed `pre_<input>` or `post_<output>`, with `__metadata__` naming the
graph signature and the step; and `generated_tokens.jsonl`, one line per
released token.

index.json holds only what was recorded: per side what is fixed for the
chat's life, and per turn its prompt and, per side, the runner's Completion
and the files the turn left; and, for a turn whose contents the index
rejected as it added the turn, which side's and why. What the index says
beyond that is derived from
those facts and the files whenever the index is read or a turn added, and is
kept in memory only: for every turn and side, which token each context
position holds, which forward pass fed it, which forward pass produced each
generated token, why the turn stopped, and which files hold the KV cache at
which moment. So the rules of derivation can change without a new format
version, and an index.json that also holds what an older server derived is
read too, its derived fields ignored. Every claim is checked against the
files and the runner's Completion; a contradiction is a runner bug, not
papered over: the turn is rejected. A turn rejected as it is added is kept,
files and all, as the evidence, and recorded as rejected; its chat ends
there. A turn that cannot be derived when the index is read, its files
missing, cut short or contradicting it, is rejected on read, in memory only,
and so is every turn after it, which needs it; the turns before it are read
as ever.

What the files show (LiteRT-LM at the runner's commit, checked on real turns):

- A decode step labelled `s` feeds position `s - 1`; the token it
  generates sits at position `s`, and is the one the jsonl releases. The
  index does not check the runtime's sampling: a greedy step's argmax is
  only named where the jsonl names no token (a stop token). On a GPU the
  logits may be F16, where two can tie at the top, or hold a NaN, or be a
  row of only -inf: greedy sampling cannot be confirmed at such a step
  (greedy_choice), so its token is marked so (`cannot_confirm`, why),
  derived on read like the rest.
- A turn's input is fed by prefill chunks and then by the first decode step,
  which feeds the last input token. Each chunk's valid positions are the
  leading run of `pre_input_pos`; the rest of its rows are padding. A chunk
  is labelled with its last valid position + 2, so the last chunk of the
  input shares its label with the first decode step.
- Turn 1's input starts with the start token. A later turn's input starts
  with the token the runtime held back at the end of the turn before, at the
  position the runner's `context_token_count` gives it: after a turn that
  ended by decoding, that turn's last generated token, a stop token or not.
- After a reply that thought, the runtime rewrites the context before the
  turn ends: prefill chunks after the decode steps feed, from the first
  decode step's position on, the reply as it renders it without the
  thoughts, and hold back its last token for the next turn. What the context
  held there before is gone. The runner's `fed_tokens` lists every row the
  turn fed, the rewrite's included, as the files must show them.
- A stop token is generated by a final decode step, counted in
  `completion_tokens`, and is neither in the jsonl nor in the content.
- A tensor a copy of the model observes (tap_model) is an output the copy
  added, keyed `post_tap_sg<S>_op<O>_out<K>`: it names its point,
  `<signature>:<O>:<K>`, and the subgraph S the signature runs, the same in
  every file of the signature; a point the signature outputs already is in
  the files under that output's own key. Only the model's scan names a
  point's key (tap_model.capture_key), so the index lists files by key
  alone.

- A PyTorch runner that observes the decoder layers' anchors writes each
  forward pass's anchor of each layer under `post_anchor_<layer>_<anchor>`
  (anchor_key), its metadata naming the same `layer` and `anchor` and the
  module it was taken at, and `observation.json` beside the tensors: what
  the turn observed, `{observe, memory_limit_bytes, captured, reason,
  snapshot_bytes}`, `captured` false with the `reason` its collector gave
  when the turn has no anchors. A side's turn says so as `observation`
  (None for a runner that wrote none). Such a turn may hold
  `execution_graph.json.gz` too (EXECUTION_GRAPH), the execution graph of
  its forward passes as pytorch-collector exports it, which the server
  keeps per model (session/model_graphs); the index lists the file and
  derives nothing from it. A module the server asked such a runner for
  beside the anchors (its Load's observeModules) is under
  `post_module_<module path>_<edge>` (module_key), its metadata naming the
  same `module` and `edge`.

- A KV cache file is LiteRT-LM's layout, [batch, kv_head, sequence,
  head_dim] for keys and [batch, kv_head, head_dim, sequence] for values,
  its sequence axis the context, unless its metadata declares its own: a
  PyTorch runner's says `layout` 'k:bhsd,v:bhsd' (Hugging Face's, its
  sequence axis the positions processed so far), and a layer that keeps a
  window of them says which in `kv_positions`, 'start-end'.

A completion recorded by a runner from before `fed_tokens`, which has
`prompt_tokens` in their place, is not read: its turn is rejected.
"""

