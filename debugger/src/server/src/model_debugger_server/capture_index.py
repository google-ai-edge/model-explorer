"""A chat's capture on disk, and the index that lines its files up.

A chat's capture lives in one directory:

  index.json
  ref/turn-<n>/<the files of turn n, named as the runner named them>
  target/turn-<n>/...

The files are LiteRT-LM's RuntimeDebugger dump: one tensor per safetensors
file, keyed `pre_<input>` or `post_<output>`, with `__metadata__` naming the
graph signature and the step; and `generated_tokens.jsonl`, one line per
released token. The index says, for every turn and side, which token each
context position holds, which forward pass fed it, which forward pass
produced each generated token, and which files hold the KV cache at which
moment. Every claim is checked against the files and the runner's Completion;
a contradiction is a runner bug and is raised, not papered over.

What the files show (LiteRT-LM at the runner's commit, checked on real turns):

- A decode step labelled `s` feeds position `s - 1`; the argmax of its
  `post_logits` is the token it generates, which sits at position `s`.
- A turn's input is fed by prefill chunks and then by the first decode step,
  which feeds the last input token. Each chunk's valid positions are the
  leading run of `pre_input_pos`; the rest of its rows are padding. A chunk
  is labelled with its last valid position + 2, so the last chunk shares its
  label with the first decode step.
- Turn 1's input is the start token and the prompt tokens. A later turn's
  input starts with the previous turn's last generated token, a stop token or
  not, at the position the previous turn gave it; the runner's prompt tokens
  do not list it. After a turn that thought, the runtime instead rolls the
  context back to that turn's last input token and feeds its own rendering
  of that turn from there, before the prompt tokens; the runner names none
  of those tokens.
- A stop token is generated by a final decode step, counted in
  `completion_tokens`, and is neither in the jsonl nor in the content.
"""

import hashlib
import json
import pathlib
import re
import types
from typing import Any

from model_debugger.v1 import runner_pb2
from model_debugger_server import errors, tensors, workspace
import numpy

FORMAT_VERSION = 1

_INDEX = 'index.json'
_TOKENS = 'generated_tokens.jsonl'
_KV_KEY = re.compile(r'(pre|post)_kv_cache_([kv])_(\d+)')
# Positions of a KV cache tensor's axes, by kind. The sequence axis is the
# one that spans the context.
_LAYOUTS = types.MappingProxyType({
    'k': ('batch', 'kv_head', 'sequence', 'head_dim'),
    'v': ('batch', 'kv_head', 'head_dim', 'sequence'),
})
_FINISH_REASONS = types.MappingProxyType({
    runner_pb2.FINISH_REASON_STOP: 'stop',
    runner_pb2.FINISH_REASON_LENGTH: 'length',
})


def completion_dict(completion: runner_pb2.Completion) -> dict:
  """Returns a runner's Completion as the index stores it.

  Raises:
    ValueError: The Completion lacks what a turn needs.
  """
  if completion.finish_reason not in _FINISH_REASONS:
    raise ValueError('The runner reported no finish reason.')
  if not completion.HasField('model_debugger'):
    raise ValueError("The runner's completion has no model_debugger part.")
  debugger = completion.model_debugger
  return {
      'content': completion.content,
      'reasoning_content': completion.reasoning_content,
      'finish_reason': _FINISH_REASONS[completion.finish_reason],
      'usage': {
          'prompt_tokens': completion.usage.prompt_tokens,
          'completion_tokens': completion.usage.completion_tokens,
          'total_tokens': completion.usage.total_tokens,
      },
      'turn': debugger.turn,
      'prompt_tokens': [
          {'id': token.id, 'text': token.text}
          for token in debugger.prompt_tokens
      ],
      'context_token_count': debugger.context_token_count,
  }


class CaptureIndex:
  """A chat's capture directory and its index.

  Attributes:
    root: The capture directory.
    sides: `index['sides']`: per side, what is fixed for the chat's life.
    turns: `index['turns']`: one entry per captured turn, in order.
  """

  def __init__(self, root: pathlib.Path, index: dict) -> None:
    """Wraps an index already read or made; use `create` or `load`."""
    self.root = root
    self._index = index
    self.sides: dict = index['sides']
    self.turns: list[dict] = index['turns']

  @classmethod
  def create(cls, root: pathlib.Path, sides: dict) -> 'CaptureIndex':
    """Starts the capture of a chat that has no turn yet.

    Args:
      root: The chat's capture directory; created.
      sides: Per side (`ref`, `target`), what is fixed for the chat's life:
        `model`, `runtime`, `host`, `device_id`, `device_name`, `load` (with
        `context_length`), `chat`, `start_token` (or None) and `stop_tokens`
        (each a list of ids, or `{"text": ...}`).
    """
    root.mkdir(parents=True, exist_ok=True)
    capture = cls(
        root, {'format_version': FORMAT_VERSION, 'sides': sides, 'turns': []}
    )
    workspace.write_json(root / _INDEX, capture._index)
    return capture

  @classmethod
  def load(cls, root: pathlib.Path) -> 'CaptureIndex':
    """Reads a chat's capture.

    Raises:
      NotFound: The chat has no capture.
      ValueError: The index is of another format version.
    """
    path = root / _INDEX
    if not path.is_file():
      raise errors.NotFound('This chat has no capture.')
    index = workspace.read_json(path)
    if index.get('format_version') != FORMAT_VERSION:
      raise ValueError(
          f'The capture in {root} has format version '
          f'{index.get("format_version")}; this server reads {FORMAT_VERSION}.'
      )
    return cls(root, index)

  def turn_directory(self, side: str, n: int) -> pathlib.Path:
    """Returns where the files of turn `n` of `side` go; made if missing."""
    directory = self.root / side / f'turn-{n}'
    directory.mkdir(parents=True, exist_ok=True)
    return directory

  def add_turn(self, n: int, prompt: str, completions: dict[str, dict]) -> None:
    """Indexes the files of turn `n`, already in its turn directories.

    Args:
      n: The turn; must follow the last captured one.
      prompt: The user message of the turn.
      completions: Per side, `completion_dict` of the runner's Completion.

    Raises:
      ValueError: The turn is out of order, or the files contradict the
        completion.
    """
    if n != len(self.turns) + 1:
      raise ValueError(f'Turn {n} cannot follow turn {len(self.turns)}.')
    if set(completions) != set(self.sides):
      raise ValueError(
          f'Turn {n} has completions for {sorted(completions)}, '
          f'not for {sorted(self.sides)}.'
      )
    previous = self.turns[-1]['sides'] if self.turns else {}
    sides = {
        side: _read_side_turn(
            self.turn_directory(side, n),
            fixed,
            completions[side],
            previous.get(side),
            n,
        )
        for side, fixed in self.sides.items()
    }
    for side, entry in sides.items():
      entry['dir'] = f'{side}/turn-{n}'
    self.turns.append({'n': n, 'prompt': prompt, 'sides': sides})
    try:
      workspace.write_json(self.root / _INDEX, self._index)
    except BaseException:
      self.turns.pop()
      raise

  def turn(self, n: int) -> dict:
    """Returns the entry of turn `n`.

    Raises:
      NotFound: Turn `n` has no capture.
    """
    if not 1 <= n <= len(self.turns):
      raise errors.NotFound(f'Turn {n} has no capture.')
    return self.turns[n - 1]

  def path(self, side: str, n: int, file: str) -> pathlib.Path:
    """Returns the path of a file of turn `n` of `side` named by the index."""
    return self.root / self.turn(n)['sides'][side]['dir'] / file


def _read_side_turn(
    directory: pathlib.Path,
    fixed: dict,
    completion: dict,
    previous: dict | None,
    n: int,
) -> dict:
  """Derives one side's entry of turn `n` from its files and its completion.

  Args:
    directory: The turn's files.
    fixed: The side's fixed info (`start_token`, `stop_tokens`, `load`).
    completion: The side's `completion_dict`.
    previous: The side's entry of turn `n - 1`, or None for turn 1.
    n: The turn.

  Raises:
    ValueError: The files contradict each other or the completion.
  """
  if completion['turn'] != n:
    raise ValueError(f'The runner calls turn {n} turn {completion["turn"]}.')
  files, calls = _scan(directory)
  released = _released(directory / _TOKENS)
  context_length = fixed['load']['context_length']
  stop_ids = {
      token[0]
      for token in fixed['stop_tokens']
      if isinstance(token, list) and len(token) == 1
  }

  prefills, decodes, start, last_input = _collect_passes(directory, calls, n)
  inputs = _build_turn_inputs(fixed, completion, previous, start, last_input, n)
  forwards = _build_forwards(directory, prefills, decodes)
  output, stop_reason = _build_turn_outputs(
      fixed, completion, forwards, released, stop_ids, last_input, n
  )
  kv = _collect_kv_snapshots(prefills, decodes, context_length)

  return {
      'completion': completion,
      'stop_reason': stop_reason,
      'input': inputs,
      'output': output,
      'forwards': forwards,
      'kv': kv,
      'files': files,
  }


def _collect_passes(
    directory: pathlib.Path,
    calls: dict[tuple[str, int], dict[str, tuple[Any, ...]]],
    turn_number: int,
) -> tuple[list[tuple[Any, ...]], list[tuple[Any, ...]], int, int]:
  """Collects and orders prefill and decode passes, verifying continuity."""
  prefills, decodes = [], []
  for (signature, step), call in calls.items():
    if signature == 'decode':
      position = _decode_position(directory, signature, step, call)
      decodes.append((step, signature, call, position))
    elif signature.startswith('prefill'):
      first, last = _prefill_positions(directory, signature, step, call)
      prefills.append((first, last, signature, step, call))
    else:
      raise ValueError(
          f'Turn {turn_number} has files of unknown signature {signature}.'
      )
  if not decodes:
    raise ValueError(f'Turn {turn_number} has no decode step.')
  prefills.sort()
  decodes.sort()
  start = prefills[0][0] if prefills else decodes[0][3]
  expected = start
  for first, last, signature, step, _ in prefills:
    if first != expected:
      raise ValueError(
          f'{signature} step {step} feeds position {first}; '
          f'position {expected} comes next.'
      )
    expected = last + 1
  for step, signature, _, position in decodes:
    if position != expected:
      raise ValueError(
          f'{signature} step {step} feeds position {position}; '
          f'position {expected} comes next.'
      )
    expected += 1
  # The first decode step feeds the last input token.
  last_input = decodes[0][3]
  return prefills, decodes, start, last_input


def _build_turn_inputs(
    fixed: dict[str, Any],
    completion: dict[str, Any],
    previous: dict[str, Any] | None,
    start: int,
    last_input: int,
    turn_number: int,
) -> list[dict[str, Any]]:
  """Builds the turn's input token list in context order."""
  prompt = completion['prompt_tokens']
  lead_count = last_input - start + 1 - len(prompt)
  if previous is None:
    lead = []
    if fixed['start_token'] is not None:
      lead = [{'id': fixed['start_token'], 'text': None, 'origin': 'start'}]
    if start != 0 or lead_count != len(lead):
      raise ValueError(
          f'Turn 1 fed positions {start}..{last_input}, but its start token '
          f'and {len(prompt)} prompt tokens take positions '
          f'0..{len(lead) + len(prompt) - 1}.'
      )
  else:
    carried = previous['output'][-1]
    if start == carried['position'] and lead_count == 1:
      lead = [
          {'id': carried['id'], 'text': carried['text'], 'origin': 'carried'}
      ]
    elif start < carried['position'] and lead_count >= 0:
      # The runtime rolled its context back to `start` and fed its own
      # rendering of the earlier turns from there, as it does after a turn
      # that thought; the runner does not say which tokens those are.
      lead = [
          {'id': None, 'text': None, 'origin': 'history'}
          for _ in range(lead_count)
      ]
    else:
      raise ValueError(
          f'Turn {turn_number} fed positions {start}..{last_input} for '
          f'{len(prompt)} prompt tokens after a turn that ended at position '
          f'{carried["position"]}.'
      )
  inputs = lead + [
      {'id': token['id'], 'text': token['text'], 'origin': 'prompt'}
      for token in prompt
  ]
  for offset, token in enumerate(inputs):
    token['position'] = start + offset
  return inputs


def _build_forwards(
    directory: pathlib.Path,
    prefills: list[tuple[Any, ...]],
    decodes: list[tuple[Any, ...]],
) -> list[dict[str, Any]]:
  """Builds the forward-pass records and reads decode logits argmax."""
  forwards = []
  for first, last, signature, step, call in prefills:
    forwards.append({
        'id': len(forwards),
        'signature': signature,
        'phase': 'prefill',
        'step': step,
        'input_positions': [first, last],
        'tensors': {key: name for key, (name, _) in sorted(call.items())},
    })
  vocabulary = None
  for step, signature, call, position in decodes:
    logits = tensors.read_tensor(directory / _need(call, 'post_logits')[0])
    rows = logits.reshape(-1, logits.shape[-1])
    if rows.shape[0] != 1:
      raise ValueError(
          f'{signature} step {step} has {rows.shape[0]} rows of logits.'
      )
    if vocabulary not in (None, rows.shape[1]):
      raise ValueError(f'{signature} step {step} changes the vocabulary size.')
    vocabulary = rows.shape[1]
    forwards.append({
        'id': len(forwards),
        'signature': signature,
        'phase': 'decode',
        'step': step,
        'input_position': position,
        'input_positions': [position],
        'tensors': {key: name for key, (name, _) in sorted(call.items())},
        'argmax': int(numpy.argmax(rows[0])),
    })
  return forwards


def _build_turn_outputs(
    fixed: dict[str, Any],
    completion: dict[str, Any],
    forwards: list[dict[str, Any]],
    released: list[tuple[int, str | None]],
    stop_ids: set[int],
    last_input: int,
    turn_number: int,
) -> tuple[list[dict[str, Any]], str]:
  """Builds the turn's generated output tokens and stop reason."""
  # Greedy sampling (top_k 1) generates each step's argmax, so the files
  # name every token; another sampler's choice is known only where the jsonl
  # names it, and its unreleased stop token is of unknown id.
  greedy = fixed['chat']['options'].get('top_k') == 1
  generated = [forward for forward in forwards if forward['phase'] == 'decode']
  if not len(released) <= len(generated) <= len(released) + 1:
    raise ValueError(
        f'Turn {turn_number} has {len(generated)} decode steps for '
        f'{len(released)} released tokens.'
    )
  output = []
  for index, forward in enumerate(generated):
    token = {
        'id': forward['argmax'] if greedy else None,
        'text': None,
        'position': forward['input_position'] + 1,
        'forward': forward['id'],
        'released': index < len(released),
    }
    if index < len(released):
      token['id'], token['text'] = released[index]
      if greedy and token['id'] != forward['argmax']:
        raise ValueError(
            f'decode step {forward["step"]} has argmax {forward["argmax"]}, '
            f'but the released token is {token["id"]} of a greedy chat.'
        )
    elif not greedy or forward['argmax'] in stop_ids:
      # The runtime releases every token but a stop token.
      token['stop'] = True
    else:
      raise ValueError(
          f'decode step {forward["step"]} generated {forward["argmax"]}, '
          'which is neither released nor a stop token.'
      )
    output.append(token)

  usage = completion['usage']
  if usage['completion_tokens'] != len(output):
    raise ValueError(
        f'The runner counts {usage["completion_tokens"]} completion tokens; '
        f'turn {turn_number} has {len(output)} decode steps.'
    )
  if completion['context_token_count'] != last_input + 1 + len(output):
    raise ValueError(
        f'The runner counts {completion["context_token_count"]} context tokens;'
        f' turn {turn_number} ends at position {last_input + len(output)}.'
    )
  ended_on_stop = output[-1].get('stop', False)
  stop_reason = (
      'eos'
      if ended_on_stop or completion['finish_reason'] == 'stop'
      else 'max_output_tokens'
  )
  return output, stop_reason


def _collect_kv_snapshots(
    prefills: list[tuple[Any, ...]],
    decodes: list[tuple[Any, ...]],
    context_length: int,
) -> list[dict[str, Any]]:
  """Collects KV cache snapshots before/after prefill and after last decode."""
  kv = []
  if prefills:
    first, _, _, step, call = prefills[0]
    layers = _kv_layers(call, 'pre', context_length)
    if layers:
      kv.append({
          'moment': 'prefill_pre',
          'step': step,
          'processed': first,
          'layers': layers,
      })
    _, last, _, step, call = prefills[-1]
    layers = _kv_layers(call, 'post', context_length)
    if layers:
      kv.append({
          'moment': 'prefill_post',
          'step': step,
          'processed': last + 1,
          'layers': layers,
      })
  for index, (step, signature, call, position) in enumerate(decodes):
    layers = _kv_layers(call, 'post', context_length)
    if layers and index != len(decodes) - 1:
      raise ValueError(
          f'{signature} step {step} wrote the KV cache before the last decode '
          'step.'
      )
    if layers:
      kv.append({
          'moment': 'terminal',
          'step': step,
          'processed': position + 1,
          'layers': layers,
      })
  return kv


def _scan(
    directory: pathlib.Path,
) -> tuple[list[dict], dict[tuple[str, int], dict[str, tuple]]]:
  """Lists a turn's files and groups its tensors by (signature, step).

  Returns:
    The files as `{path, size, sha256}`, and per (signature, step) the
    tensors as `{key: (file name, TensorHeader)}`.
  """
  files, calls = [], {}
  names = sorted(path.name for path in directory.iterdir())
  if _TOKENS not in names:
    raise ValueError(f'The capture in {directory} has no {_TOKENS}.')
  for name in names:
    path = directory / name
    with open(path, 'rb') as file:
      digest = hashlib.file_digest(file, 'sha256').hexdigest()
    files.append({'path': name, 'size': path.stat().st_size, 'sha256': digest})
    if name == _TOKENS:
      continue
    if not name.endswith('.safetensors'):
      raise ValueError(f'The capture holds an unexpected file, {name}.')
    header = tensors.read_header(path)
    signature = header.metadata.get('signature')
    step = header.metadata.get('step', '')
    if not signature or not step.isdigit():
      raise ValueError(f'{name} names no signature and step.')
    if not header.key.startswith(('pre_', 'post_')):
      raise ValueError(f'{name} holds {header.key}, not an input or output.')
    call = calls.setdefault((signature, int(step)), {})
    if header.key in call:
      raise ValueError(
          f'{name} and {call[header.key][0]} both hold {header.key} of '
          f'{signature} step {step}.'
      )
    call[header.key] = (name, header)
  return files, calls


def _released(path: pathlib.Path) -> list[tuple[int, str | None]]:
  """Returns the released tokens of a turn as (id, text or None)."""
  tokens = []
  for number, line in enumerate(path.read_text('utf-8').split('\n'), 1):
    if not line.strip():
      continue
    record = json.loads(line)
    ids = record.get('token_ids')
    if not (
        isinstance(ids, list)
        and len(ids) == 1
        and isinstance(ids[0], list)
        and len(ids[0]) == 1
        and type(ids[0][0]) is int
    ):
      raise ValueError(
          f'{_TOKENS} line {number} is not one token of one candidate.'
      )
    texts = record.get('texts')
    text = None
    if isinstance(texts, list) and len(texts) == 1:
      text = texts[0]
    tokens.append((ids[0][0], text))
  return tokens


def _need(call: dict, key: str) -> tuple:
  """Returns the (file name, header) of `key` in a call, or raises."""
  if key not in call:
    names = ', '.join(sorted(name for name, _ in call.values()))
    raise ValueError(f'The call with files {names} has no {key}.')
  return call[key]


def _decode_position(
    directory: pathlib.Path, signature: str, step: int, call: dict
) -> int:
  """Returns the position a decode step feeds, checked against its step."""
  positions = tensors.read_tensor(directory / _need(call, 'pre_input_pos')[0])
  positions = positions.reshape(-1)
  if positions.size != 1:
    raise ValueError(
        f'{signature} step {step} feeds {positions.size} positions.'
    )
  position = int(positions[0])
  if position != step - 1:
    raise ValueError(f'{signature} step {step} feeds position {position}.')
  return position


def _prefill_positions(
    directory: pathlib.Path, signature: str, step: int, call: dict
) -> tuple[int, int]:
  """Returns the first and last position a prefill chunk feeds.

  The valid rows are the leading run of consecutive positions; the padding
  after them has position 0. A boolean mask must attend from exactly as many
  rows.
  """
  positions = tensors.read_tensor(directory / _need(call, 'pre_input_pos')[0])
  positions = positions.reshape(-1)
  count = 1
  while count < positions.size and positions[count] == positions[count - 1] + 1:
    count += 1
  first = int(positions[0])
  if 'pre_mask' in call and call['pre_mask'][1].dtype == 'BOOL':
    mask = tensors.read_tensor(directory / call['pre_mask'][0])
    attending = int(mask.reshape(-1, mask.shape[-1]).any(axis=1).sum())
    if attending != count:
      raise ValueError(
          f'{signature} step {step} feeds {count} positions, but its mask '
          f'attends from {attending} rows.'
      )
  return first, first + count - 1


def _kv_layers(call: dict, moment: str, context_length: int) -> list[dict]:
  """Returns the KV cache tensors of a call at `pre` or `post`, by layer."""
  layers: dict[int, dict[str, Any]] = {}
  for key, (name, header) in call.items():
    match = _KV_KEY.fullmatch(key)
    if match is None or match.group(1) != moment:
      continue
    kind = match.group(2)
    shape = list(header.shape)
    sequence_axis = _LAYOUTS[kind].index('sequence')
    fits = len(shape) == 4 and shape[sequence_axis] == context_length
    layers.setdefault(int(match.group(3)), {})[
        'key' if kind == 'k' else 'value'
    ] = {
        'file': name,
        'dtype': header.dtype,
        'shape': shape,
        'layout': list(_LAYOUTS[kind]) if fits else None,
    }
  for layer, parts in layers.items():
    if len(parts) != 2:
      raise ValueError(
          f'Layer {layer} has a {moment} KV cache of one kind only.'
      )
  return [{'layer': layer, **layers[layer]} for layer in sorted(layers)]
